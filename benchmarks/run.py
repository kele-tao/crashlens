def build_log(blocks: int) -> str:
    """Deterministic mixed-language log of *blocks* crash records."""
    chunks: list[str] = []
    for index in range(blocks):
        _name, template = TEMPLATES[index % len(TEMPLATES)]
        minute = index // 60 % 60
        second = index % 60
        chunks.append(template.format(minute=minute, second=second))
    return "\n".join(chunks)


def time_once(text: str) -> tuple[float, int, int]:
    start = time.perf_counter()
    crashes = parse_text(text)
    clusters = rank(cluster_crashes(crashes))
    elapsed = time.perf_counter() - start
    return elapsed, len(crashes), len(clusters)


def measure(blocks: int) -> dict[str, object]:
    text = build_log(blocks)
    payload_bytes = len(text.encode("utf-8"))
    samples: list[float] = []
    crashes = clusters = 0
    for _ in range(REPEATS):
        elapsed, crashes, clusters = time_once(text)
        samples.append(elapsed)
    best = min(samples)
    return {
        "blocks": blocks,
        "bytes": payload_bytes,
        "lines": text.count(chr(10)) + 1,
        "megabytes": round(payload_bytes / 1_000_000, 2),
        "crashes": crashes,
        "clusters": clusters,
        "best_ms": round(best * 1000, 1),
        "median_ms": round(statistics.median(samples) * 1000, 1),
        "throughput_mb_s": round(payload_bytes / 1_000_000 / best, 1),
    }


def main() -> int:
    machine = {
        "python": platform.python_version(),
        "platform": platform.platform(),
        "processor": platform.machine(),
        "seed": SEED,
        "repeats": REPEATS,
    }
    # 1334 blocks ~ 10k lines, 17000 blocks ~ 5 MB: the two sizes the project
    # spec names explicitly.
    results = [measure(blocks) for blocks in (1000, 1334, 5000, 10000, 17000)]
    payload = {"machine": machine, "results": results}
    out = ROOT / "benchmarks" / "results.json"
    out.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    table = [
        "| crash records | lines | input size | crashes parsed | clusters | best | median | MB/s |",
        "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for row in results:
        table.append(
            "| {blocks} | {lines} | {megabytes} MB | {crashes} | {clusters} | {best_ms} ms | "
            "{median_ms} ms | {throughput_mb_s} |".format(**row)
        )
    markdown = "\n".join(
        [
            "# Benchmark results",
            "",
            "Generated by " + TICK + "python benchmarks/run.py" + TICK + " on:",
            "",
            "- Python " + machine["python"],
            "- " + machine["platform"] + " (" + machine["processor"] + ")",
            "- seed " + str(machine["seed"]) + ", best of " + str(machine["repeats"]) + " runs",
            "",
            *table,
            "",
            "The input is a deterministic mixed log of Python (single and chained),",
            "Node.js, Java, Go and Rust crash records, so the parse cost covers all",
            "five parsers rather than one.  The best column is the fastest wall-clock",
            "run; median is the middle of five runs.  Parsing and clustering are",
            "measured together, which is what the CLI does.",
            "",
        ]
    )
    (ROOT / "benchmarks" / "RESULTS.md").write_text(markdown, encoding="utf-8")
    print(markdown)
    return 0


if __name__ == "__main__":
    sys.exit(main())
